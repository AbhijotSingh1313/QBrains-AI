export function getLocalizedVideo(video, langCode = 'en') {
  if (!video || langCode === 'en') return video;
  const trans = VIDEO_TRANSLATIONS[video.id];
  if (!trans || !trans[langCode]) return video;
  const loc = trans[langCode];
  return {
    ...video,
    topic: loc.topic || video.topic,
    description: loc.description || video.description,
    whyRecommended: loc.whyRecommended || video.whyRecommended
  };
}
