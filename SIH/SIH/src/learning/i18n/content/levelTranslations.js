export function getLocalizedLevel(level, langCode = 'en') {
  if (!level) return null;
  const levelData = LEVEL_TRANSLATIONS[level.id];
  if (!levelData) return level;
  
  const trans = levelData[langCode] || levelData.en || {};
  return {
    ...level,
    title: trans.title || level.title,
    subtitle: trans.subtitle || level.subtitle,
    modules: level.modules ? level.modules.map(m => ({
      ...m,
      title: (trans.modules && trans.modules[m.id]) || m.title
    })) : level.modules
  };
}
