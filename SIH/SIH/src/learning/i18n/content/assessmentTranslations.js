export function getLocalizedQuestion(question, langCode = 'en') {
  if (!question || langCode === 'en') return question;
  
  const trans = ASSESSMENT_TRANSLATIONS[question.id];
  if (!trans || !trans[langCode]) return question;

  const loc = trans[langCode];
  
  // Return localized question while preserving question.id, type, competency
  return {
    ...question,
    question: loc.question || question.question,
    options: loc.options || question.options,
    correctAnswer: loc.correctAnswer || question.correctAnswer,
    explanation: loc.explanation || question.explanation
  };
}
